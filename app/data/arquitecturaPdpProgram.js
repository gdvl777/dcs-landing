export function isCheckoutReady(program = arquitecturaPdpProgram) {
  return (
    program.enrollment.status === "open" &&
    program.checkout.enabled === true &&
    Boolean(program.checkout.url) &&
    Boolean(program.enrollment.priceLabel)
  );
}

export function buildWhatsAppUrl(text, program = arquitecturaPdpProgram) {
  return `https://wa.me/${program.brand.whatsappNumber}?text=${encodeURIComponent(text)}`;
}

export function getPrimaryCtaLabel(program = arquitecturaPdpProgram) {
  return isCheckoutReady(program)
    ? "Inscribirme al curso PANSI"
    : "Consultar mi inscripción";
}
